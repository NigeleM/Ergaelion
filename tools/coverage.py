"""Write docs/COVERAGE.md: how the catalogue is spread across families, topics and areas.

Run from the project root:  python3 tools/coverage.py
A game can sit in more than one family or topic, so percentages can add up to more than 100.
"""

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gtplaybook.catalog import load_games  # noqa: E402

DATA = ROOT / "gtplaybook" / "data"


def main():
    games = {g["id"]: g for g in load_games()}
    total = len(games)
    areas = json.loads((DATA / "areas.json").read_text(encoding="utf-8"))
    family_ids, area_ids = {}, {}
    for family in areas:
        family_ids[family["family"]] = set()
        for sub in family["subdomains"]:
            ids = set(sub["games"]) & set(games)
            area_ids[(family["family"], sub["name"])] = ids
            family_ids[family["family"]] |= ids
    topic_count = Counter(d for g in games.values() for d in g["domains"])
    tags = sum(topic_count.values())

    lines = [
        "# Catalogue coverage",
        "",
        f"Generated by `tools/coverage.py`. {total} games in total. A game can sit in more than one family or topic, so the percentages can add up to more than 100.",
        "",
        "## Families",
        "",
        "| Games | Share | Family |",
        "| ---: | ---: | --- |",
    ]
    for name, ids in sorted(family_ids.items(), key=lambda x: (-len(x[1]), x[0])):
        lines.append(f"| {len(ids)} | {100 * len(ids) / total:.1f}% | {name} |")
    lines += [
        "",
        "## Topics",
        "",
        "Topics come from each game's domain tags. The last column is the share of all tags.",
        "",
        "| Games | Share of games | Share of tags | Topic |",
        "| ---: | ---: | ---: | --- |",
    ]
    for name, count in topic_count.most_common():
        lines.append(f"| {count} | {100 * count / total:.1f}% | {100 * count / tags:.1f}% | {name} |")
    lines += [
        "",
        "## Areas",
        "",
        "Areas are the sub-domains inside each family.",
        "",
        "| Games | Family | Area |",
        "| ---: | --- | --- |",
    ]
    for (family, sub), ids in sorted(area_ids.items(), key=lambda x: (-len(x[1]), x[0])):
        if ids:
            lines.append(f"| {len(ids)} | {family} | {sub} |")
    out = ROOT / "docs" / "COVERAGE.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({total} games)")


if __name__ == "__main__":
    main()
